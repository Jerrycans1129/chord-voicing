import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const git=args=>execFileSync('git',args,{cwd:fileURLToPath(root),encoding:'utf8'}).trim();
const revision=git(['rev-parse','--short=7','HEAD']);
const changed=[...git(['diff','HEAD','--name-only']).split('\n'),...git(['ls-files','--others','--exclude-standard']).split('\n')];
// Generated metadata alone must not turn the next identical build into a dev build.
const dirty=changed.some(path=>path&&!['dist/build.js','dist/sw.js'].includes(path));
writeFileSync(new URL('dist/build.js',root),`// Generated by npm run build; commit identifies the source checkout.\nexport const BUILD_REVISION=${JSON.stringify(revision+(dirty?'-dev':''))};\n`);
const hash=createHash('sha256');
for(const name of readdirSync(new URL('dist/',root)).sort().filter(name=>name!=='sw.js'))hash.update(name).update(readFileSync(new URL(`dist/${name}`,root)));
const fingerprint=hash.digest('hex').slice(0,12),sw=new URL('dist/sw.js',root);
writeFileSync(sw,readFileSync(sw,'utf8').replace(/const CACHE_NAME = .*;/, 'const CACHE_NAME = `${CACHE_PREFIX}v23-'+revision+'-'+fingerprint+'`;'));
